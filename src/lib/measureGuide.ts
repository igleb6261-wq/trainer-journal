/** Короткая подпись для карточек, таблицы и графика */
export const shortLabel = (m: Metric) => m.label.replace(/,\s*рука расслаблена$/i, '').replace(/\s*\(по пупку\)$/i, '')

/**
 * Одноразовая правка списка показателей:
 * убираем дубли (живот = талия, ширина спины = плечи, таз = ягодицы),
 * обновляем названия. Значения из дублей переносятся, если основного значения нет;
 * сами старые значения в записях не удаляются.
 */
export async function migrateMetrics() {
  const v = await getSetting<number>('metricsVersion', 1)
  if (v >= 2) return
  const MERGE: Record<string, string> = { belly: 'waist', back: 'shoulders', pelvis: 'glutes' }
  await db.transaction('rw', db.measurements, db.settings, async () => {
    const all = await db.measurements.toArray()
    for (const m of all) {
      let changed = false
      const values = { ...m.values }
      for (const [from, to] of Object.entries(MERGE)) {
        if (values[from] !== undefined && values[to] === undefined) {
          values[to] = values[from]
          changed = true
        }
      }
      if (changed) await db.measurements.update(m.id, { values })
    }
    const s = await db.settings.get('metrics')
    if (s) {
      const saved = s.value as Metric[]
      const has = new Set(saved.map((m) => m.key))
      const list = saved
        // дубль остаётся только если основного показателя в списке нет — тогда он им и становится
        .map((m) => (m.key in MERGE && !has.has(MERGE[m.key]) ? { ...m, key: MERGE[m.key] } : m))
        .filter((m) => !(m.key in MERGE))
        .map((m) => {
          const d = DEFAULT_METRICS.find((x) => x.key === m.key)
          return d ? { ...m, label: d.label } : m
        })
      await setSetting('metrics', list)
    }
    await setSetting('metricsVersion', 2)
  })
}
